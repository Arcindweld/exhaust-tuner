const { chromium } = require('playwright');
(async () => {
  const b = await chromium.launch(); const pg = await b.newPage({ viewport: { width: 1280, height: 900 } });
  const errs = []; pg.on('pageerror', e => errs.push(e.message));
  const fails = []; const ok = (c, m) => { if (!c) fails.push(m); console.log((c ? 'PASS ' : 'FAIL ') + m); };
  await pg.goto('file://' + process.cwd()+'/index.html');
  await pg.evaluate(() => { window.__sent = []; window.adsk = { fusionSendData: (a, d) => { window.__sent.push([a, d]); return Promise.resolve(JSON.stringify({ ok: true, msg: 'stub', route_ok: true, items: [] })); } }; });
  const setv = (id, v) => pg.evaluate(([id, v]) => { const el = document.getElementById(id); el.value = v; el.dispatchEvent(new Event(el.tagName === 'SELECT' ? 'change' : 'input', { bubbles: true })); }, [id, v]);
  await pg.evaluate(() => { location.hash = 'parts'; }); await pg.waitForTimeout(300);
  const kinds = await pg.$$eval('#p-kind option', o => o.map(x => x.value));
  ok(kinds.indexOf('mafbung') >= 0, 'mafbung kind listed');
  await setv('p-kind', 'mafbung'); await pg.waitForTimeout(100);
  const n = await pg.$$eval('#p-list .pcard', c => c.length);
  const t = await pg.$eval('#p-list', e => e.innerText);
  ok(n === 52, '52 MAF bung cards (' + n + ')');
  ok(!/\bNaN\b|\bundefined\b|\[object/.test(t), 'no NaN/undefined in cards');
  ok(/card pad/.test(t) && /slot bung/.test(t) && /for 4 in tube/.test(t) && /pad 2 in × 2 in × 1 in tall/.test(t), 'dims text: style, tube, pad size');
  ok(/placement guidance/i.test(t) && /8-10/.test(t), 'maker guidance shown (Spectre 8-10 in)');
  const brands = await pg.$$eval('#p-brand option', o => o.map(x => x.value).filter(Boolean));
  ok(brands.indexOf('ICT Billet') >= 0 && brands.indexOf('Ticon Industries') >= 0 || brands.some(x => /Ticon/.test(x)), 'brands include ICT and Ticon (' + brands.length + ')');
  await setv('p-brand', 'ICT Billet'); await pg.waitForTimeout(80);
  await pg.click('#p-list button[data-addpart]'); await pg.waitForTimeout(60);
  const rows = await pg.$$eval('#p-build tbody tr', r => r.length);
  ok(rows === 1, 'pad added to the build list');
  await pg.evaluate(() => { location.hash = 'intake'; }); await pg.waitForTimeout(300);
  await setv('i-ind', 'na'); await pg.waitForTimeout(200); await pg.evaluate(() => { window.__sent = []; });
  await pg.click('#fx-intake button[data-fx="routeParts"]'); await pg.waitForTimeout(300);
  const pay = await pg.evaluate(() => window.__sent.map(s => [s[0], JSON.parse(s[1])]).find(s => s[0] === 'route'));
  const pad = pay && (pay[1].parts || []).find(x => x.kind === 'mafbung');
  console.log('  pad payload:', JSON.stringify(pad && { attach: pad.attach, tube_od_in: pad.tube_od_in, prefer: pad.prefer, lead_in_in: pad.lead_in_in, lead_out_in: pad.lead_out_in, min_from_end_in: pad.min_from_end_in, padL: pad.padL, padH: pad.padH }));
  ok(pad && pad.attach && pad.prefer === 'mid' && pad.tube_od_in > 2 && pad.min_from_end_in === 8 && pad.lead_in_in >= 2.9, 'NA route payload carries the pad as a mid-straight fitting');
  await pg.evaluate(() => { document.body.classList.add('expert'); }); await setv('i-ind', 'turbo'); await pg.waitForTimeout(300); await pg.evaluate(() => { window.__sent = []; });
  await pg.click('#fx-intake button[data-fx="routeParts"]'); await pg.waitForTimeout(300);
  const pay2 = await pg.evaluate(() => window.__sent.map(s => [s[0], JSON.parse(s[1])]).find(s => s[0] === 'route'));
  console.log('  boosted payload kinds:', pay2 && (pay2[1].parts||[]).map(x=>x.kind).join(','), pay2 ? '' : 'NO ROUTE SENT ' + JSON.stringify(await pg.evaluate(() => window.__sent.map(s => s[0]))));
  const fxt = await pg.$eval('#fx-intake', e => e.innerText);
  ok((!pay2 && /Add parts to the build list first/.test(fxt)) || (pay2 && !(pay2[1].parts || []).find(x => x.kind === 'mafbung')), 'boosted charge-pipe route leaves the pad out');
  const method = await pg.evaluate(() => document.body.innerHTML.indexOf('Weld-on MAF bungs and pads') >= 0);
  ok(method, 'Method note present');
  ok(errs.length === 0, 'no page errors ' + errs.join(' | '));
  console.log(fails.length ? 'FAILS: ' + fails.length : 'ALL PASS');
  await b.close();
})();
